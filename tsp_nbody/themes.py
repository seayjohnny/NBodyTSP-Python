def _f2i(r, g, b):
    """Convert 0-1 float RGB to 0-255 int RGB."""
    return (int(r * 255), int(g * 255), int(b * 255))


def _i2f(r, g, b):
    """Convert 0-255 int RGB to 0-1 float RGB."""
    return (r / 255.0, g / 255.0, b / 255.0)


